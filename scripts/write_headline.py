#!/usr/bin/env python3
"""Write results/HEADLINE.md from the result files, so the headline numbers
in the docs always match what the scripts produced.

    python3 scripts/write_headline.py            # -> results/HEADLINE.md
"""
import json
import os
import sys

R = os.environ.get("HEADLINE_RESULTS_DIR", "results")


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p)) if os.path.isfile(p) else None


def pct(x, d=1):
    return f"{100 * x:.{d}f}%"


def rate(r, d=1):
    """Percentage from a {"k", "n"} record, computed from the counts."""
    return f"{100 * r['k'] / r['n']:.{d}f}%" if r["n"] else "n/a"


def ms(m, k="f1"):
    v = m[k]
    return f"{v['mean']:.3f} ± {v['std']:.3f}"


def main() -> int:
    lab = load("cargo_label_report.json")
    ext = load("extraction_report.json")
    fill = load("github_fill_report.json")
    scope = load("scope_coverage.json")
    grp = load("section_4_grouped_repo_5seed.json")
    crate = load("section_4_grouped_crate_5seed.json")
    temp = load("section_4_temporal_repo.json")
    abl = load("feature_ablation_rebuilt_cargo_rf.json")
    san = load("label_sanity_rebuilt_cargo_summary.json")
    down = load("downstream_impact.json")
    aud = load("label_audit/summary.json")
    L = []
    w = L.append
    w("# Headline numbers\n")
    w("Generated by `scripts/write_headline.py` from the files in `results/`; "
      "do not edit by hand.\n")
    w("Dataset: `data/cratesbump.csv.gz`. Every crate in the crates.io dump of "
      "2026-10-12 with at least two non-yanked releases published before "
      "2026-09-14T00:00Z; Cargo labels; at most 100 pairs per crate and 5,000 "
      "per name family.\n")
    if scope:
        w("## Scope\n")
        w(f"- {scope['n_crates_in_scope']:,} of {scope['n_crates_total']:,} crates "
          f"({scope['pct_crates_in_scope']}%) are in scope; they account for "
          f"{scope['pct_downloads_in_scope']}% of all crates.io downloads.")
        w(f"- {scope['n_in_scope_never_stable_1_0']:,} of them "
          f"({scope['pct_in_scope_never_stable_1_0']}%) never had a stable 1.0 release; "
          f"they carry {scope['pct_downloads_in_scope_never_stable_1_0']}% of all downloads.\n")
    if lab:
        st = lab["status"]
        w("## Build (`results/cargo_label_report.json`)\n")
        if ext:
            w(f"- In scope: {ext['crates_in_scope']:,} crates; {ext['crates_with_no_pair_under_plan_pairs']:,} "
              f"form no pair; {ext['crates_with_pairs_not_extracted']:,} with pairs could not be "
              f"extracted (CDN status of a needed tarball: {ext['not_extracted_by_cdn_status']}; "
              f"`results/extraction_report.json`).")
        w(f"- Extractor output: {lab['input_rows']:,} pairs from {lab['input_crates']:,} crates.")
        if lab.get("checks"):
            c = lab["checks"]
            w(f"- Checks run: predecessor reproduces the naive label "
              f"({'yes' if c.get('predecessor_reproduces_naive_label') else 'no'}), "
              f"`rdtd` equals the gap to the predecessor "
              f"({'yes, ±' + str(c.get('rdtd_tolerance_days')) + ' days' if c.get('rdtd_matches_predecessor_gap') else 'no'}).")
        w(f"- Kept after predecessor and `rdtd` verification: {st.get('kept', 0):,} "
          f"(no predecessor in the dump: {st.get('no_predecessor_in_dump', 0):,}; "
          f"predecessor disagrees with the extractor's label: "
          f"{st.get('predecessor_disagrees_with_extractor', 0):,}; "
          f"`rdtd` disagrees: {st.get('rdtd_disagrees_with_predecessor', 0):,}).")
        w(f"- Dropped by the caps: {st.get('dropped_by_cap', 0):,}.")
        w(f"- **Headline file: {lab['output_rows']:,} pairs from {lab['output_crates']:,} crates.**")
        if "rows_with_repository" in st:
            w(f"- Rows with a `repository`: {st['rows_with_repository']:,} "
              f"({pct(st['rows_with_repository'] / lab['output_rows'])}), "
              f"{st['distinct_repositories']:,} distinct repositories.")
        w(f"- Cargo labels: {lab['cargo_label_pct']}; naive labels: {lab['naive_label_pct']}.")
        w(f"- The labels differ on {lab['flips']:,} pairs ({lab['flips_pct']}%), exactly the "
          f"pairs whose new version is below 1.0.0:")
        for k, v in lab["flip_cases"].items():
            w(f"  - {k}: {v['n']:,} ({v['pct_of_flips']}%)")
        w("")
    if fill:
        w("## GitHub features (`results/github_fill_report.json`)\n")
        w(f"- {fill['pct_all_rows_nonzero_after']}% of pairs have at least one non-zero "
          f"GitHub feature; {fill['rows_without_github_repo']:,} rows have no GitHub repository; "
          f"{fill['github_repos']:,} repositories ({fill['repos_without_commits']:,} could not be "
          f"cloned or have no commits).\n")
    for title, res in (("Held-out repositories (headline; 5 seeds)", grp),
                       ("Held-out crates (5 seeds; shows leakage through shared repositories)", crate),
                       ("Temporal split (by repository)", temp)):
        if not res:
            continue
        sp = list(res["splits"].values())[0]
        w(f"## {title}\n")
        sz = sp.get("sizes", [{}])[0]
        if sz:
            w(f"Test fold (seed 42): {sz.get('test_rows', 0):,} pairs from "
              f"{sz.get('test_crates', 0):,} crates; train {sz.get('train_rows', 0):,} pairs. "
              f"Test-group overlap {pct(sp['test_group_overlap'])}.\n")
        w("| Model | Macro-F1 | MCC |")
        w("|---|---|---|")
        for name, m in sp["models"].items():
            w(f"| {name} | {ms(m)} | {ms(m, 'mcc')} |")
        w("")
    if abl:
        w(f"## Ablation (Random Forest, first held-out-repository fold, "
          f"baseline macro-F1 {abl['baseline_f1']:.3f})\n")
        for r in abl.get("family_ablations", []):
            w(f"- family {r['family']}: drop {r['drop_mean']:+.3f} ± {r['drop_std']:.3f}")
        w("- top single features: " + ", ".join(
            f"`{r['feature']}` {r['drop_mean']:+.3f}" for r in abl["ablations"][:10]))
        w("")
    if san:
        w("## Internal consistency probe\n")
        w(f"- {san['n_flagged']:,} of {san['n_rows']:,} pairs ({san['pct_flagged']:.1f}%) "
          f"flagged (see `results/label_sanity_rebuilt_cargo_summary.json`).\n")
    if down:
        d = down["dependent_relations"]
        w("## Dependents of pre-1.0 breaking releases (`results/downstream_impact.json`)\n")
        w(f"- {down['n_problem_pairs']:,} releases are naive-minor but Cargo-major.")
        w(f"- Dependency relations: {d['protected']:,} protected, {d['exposed']:,} exposed "
          f"({d['pct_exposed_of_tracking']}% of those tracking the previous release); "
          f"{down['pairs_with_exposed_dependent']:,} releases "
          f"({down['pct_pairs_with_exposed_among_all']}%) exposed any dependent.")
        w(f"- Exposed relations by requirement shape: {down['exposed_relations_by_req_shape']}.")
        w(f"- Requirement shapes over all {down['req_population']['total_normal_dep_rows']:,} "
          f"normal dependency declarations: {down['req_population']['pct_by_shape']}.\n")
    if aud:
        f = aud["flags"]
        w("## External API audit (`results/label_audit/summary.json`)\n")
        w(f"- Sample: {aud['sampling']}; the tool checked {aud['n_evaluated']}.")
        w(f"- Flags (tool says a bigger bump was needed): minor {f['minor']['k']}/{f['minor']['n']}, "
          f"patch {f['patch']['k']}/{f['patch']['n']}; "
          f"{f['flagged_minor_that_are_0y_patch_number_bumps']} flagged minor releases are 0.y "
          f"patch-number bumps.")
        c = aud.get("confirmed")
        if c:
            g = c["genuine"]
            w(f"- **Confirmed by hand: minor {g['minor']['k']}/{g['minor']['n']} "
              f"({rate(g['minor'])}, 95% CI {pct(g['minor']['wilson95'][0])}–"
              f"{pct(g['minor']['wilson95'][1])}), patch {g['patch']['k']}/{g['patch']['n']} "
              f"({rate(g['patch'])}, CI {pct(g['patch']['wilson95'][0])}–"
              f"{pct(g['patch']['wilson95'][1])}).**")
            w(f"- Not genuine: {c['not_genuine_reasons']}.")
            if isinstance(c["stops_code_compiling"], dict):
                s = c["stops_code_compiling"]["minor_plus_patch"]
                w(f"- Stops dependents' code compiling: {s['k']}/{s['n']} ({rate(s)}).")
        o = f["lints_0_22_only"]
        w(f"- Flags restricted to lints that existed in cargo-semver-checks 0.22.0: "
          f"minor {o['minor']['k']}/{o['minor']['n']}, patch {o['patch']['k']}/{o['patch']['n']}.\n")
    pn = load("paper_numbers.json")
    if pn:
        g, a = pn["github_zeros"], pn["audit"]
        sp = g["no_activity_split_approx"]
        w("## Further paper numbers (`results/paper_numbers.json`, `make paper-numbers`)\n")
        w(f"- All 11 GitHub features zero: {g['all_github_features_zero']['pct']}% of pairs: "
          f"no repository {g['no_repository']['pct']}%, other host {g['other_host']['pct']}%, "
          f"GitHub repository not cloned {g['repo_not_cloned']['pct']}%, nothing in the window "
          f"{g['no_activity_in_window']['pct']}% (CSV-only split: "
          f"{sp['inside_commit_span_pct']}% inside the repository's commit span, median gap "
          f"{sp['inside_median_gap_hours']} h; {sp['outside_commit_span_pct']}% outside it).")
        b = g["known_bug_unusual_github_url"]
        w(f"- Known bug, unusual GitHub URLs: {b['rows']} pairs of {b['crates']} crates.")
        s = a.get("no_library_split")
        if s:
            w(f"- Audit, no library target: {a['no_library_target']} ({s['command_line_only']} "
              f"command-line only, {s['macro_crates']} macro crates); "
              f"{a['no_longer_build_resolve_or_download']} no longer build, resolve or download "
              f"({a['feature_conflict_build_failures']['count']} by a feature-conflict log "
              f"heuristic).")
        y = a["checkable_library_releases_by_year"]
        w(f"- Checkable library releases: {y['before_2020']['pct']}% before 2020, "
          f"{y['from_2020']['pct']}% from 2020 on.")
        z = a["checked_minor_0yz"]
        w(f"- {z['zero_major']} of {z['n_minor']} checked minor releases are 0.y.z "
          f"({z['breaks_zero_major']} of the {z['breaks']} breaks).")
        p = a["confirmed_without_prereleases"]
        w(f"- Confirmed rates without pre-releases: minor {p['minor']['pct']}%, "
          f"patch {p['patch']['pct']}%; minor and patch combined "
          f"{a['confirmed_minor_plus_patch']['pct']}%.\n")
    w("## Earlier model settings\n")
    w("Same commands with the hyperparameters used before re-tuning; the current "
      "settings come from `results/tuning_results.json`.\n")
    for d, label in (("original_params", "original (May 2026) settings, `results/original_params/`"),
                     ("params_tune160k", "160,002-pair search, `results/params_tune160k/`")):
        rg = load(f"{d}/section_4_grouped_repo_5seed.json")
        cr = load(f"{d}/section_4_grouped_crate_5seed.json")
        ab = load(f"{d}/feature_ablation_rebuilt_cargo_rf.json")
        if not rg:
            continue
        m = rg["splits"]["grouped"]["models"]
        ens = [m[n]["f1"]["mean"] for n in ("XGBoost", "Random Forest", "LightGBM",
                                            "Hist Gradient Boosting", "Gradient Boosting")]
        line = (f"- {label}: held-out repositories, tree ensembles {min(ens):.3f}–{max(ens):.3f} "
                f"(Random Forest {m['Random Forest']['f1']['mean']:.3f})")
        if cr:
            line += (f"; held-out crates, Random Forest "
                     f"{cr['splits']['grouped']['models']['Random Forest']['f1']['mean']:.3f}")
        if ab and ab.get("family_ablations"):
            line += "; family drops " + ", ".join(
                f"{r['family']} {r['drop_mean']:+.3f}" for r in ab["family_ablations"])
        w(line + ".")
    w("")
    out = os.path.join(R, "HEADLINE.md")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"wrote {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
