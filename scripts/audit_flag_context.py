#!/usr/bin/env python3
"""Context for hand-reviewing the audit's flagged pairs (shipped_lower).

For every flagged pair in <audit_dir>/per_pair.jsonl, downloads both
`.crate` tarballs into <work_dir> (unpacked only, never built) and records
signals that often make a flagged API break harmless in practice:

  has_bin_target    the crate also ships binaries (src/main.rs, src/bin/, [[bin]])
  private_items     failing items whose path contains __private / private
  doc_hidden_items  failing items marked #[doc(hidden)] near their definition
  generated         the files holding failing items say they are generated
  dependents        crates whose latest release depends on it (normal deps, dump)
  eq_pinned_share   share of those dependents that pin it with `=`

Writes <audit_dir>/flag_context.csv. The verdicts themselves go into
<audit_dir>/hand_review.csv after reading both versions' source.

    python3 scripts/audit_flag_context.py results/label_audit .dump_cache/2026-10-12-020016 \\
        --work-dir .audit_work/flag_context
"""
import argparse
import csv
import json
import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from label_audit_cargo_semver_checks import download_crate  # noqa: E402

GEN_RE = re.compile(r"@generated|do not edit|automatically generated|generated automatically|"
                    r"auto-generated|generated by|code generator",
                    re.I)
ITEM_FILE_RE = re.compile(r"in file (/work/[^:]+):(\d+)")


def item_files(items, root):
    """(local path, line) for each failing item's source location."""
    out = []
    for it in items:
        m = ITEM_FILE_RE.search(it)
        if m:
            out.append((os.path.join(root, m.group(1)[len("/work/"):]), int(m.group(2))))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("audit_dir")
    ap.add_argument("dump_dir")
    ap.add_argument("--work-dir", default=".audit_work/flag_context")
    args = ap.parse_args()
    rows = [json.loads(l) for l in open(os.path.join(args.audit_dir, "per_pair.jsonl"))]
    flagged = [r for r in rows if r["outcome"] == "shipped_lower"]
    names = {r["package"] for r in flagged}

    # Reverse dependencies from the dump: latest release of each dependent.
    data = os.path.join(args.dump_dir, "data")
    csv.field_size_limit(1 << 30)
    id2name = {}
    for r in csv.DictReader(open(os.path.join(data, "crates.csv"), newline="", encoding="utf-8")):
        id2name[r["id"]] = r["name"]
    name2id = {v: k for k, v in id2name.items()}
    targets = {name2id[n] for n in names if n in name2id}
    latest = {}                     # dependent crate id -> (created_at, version id)
    vcrate = {}
    for r in csv.DictReader(open(os.path.join(data, "versions.csv"), newline="", encoding="utf-8")):
        if r.get("yanked", "f") in ("t", "true", "True", "1"):
            continue
        vcrate[r["id"]] = r["crate_id"]
        cur = latest.get(r["crate_id"])
        if cur is None or r["created_at"] > cur[0]:
            latest[r["crate_id"]] = (r["created_at"], r["id"])
    latest_vids = {v[1] for v in latest.values()}
    reqs = defaultdict(list)        # target id -> [req of each dependent's latest release]
    for r in csv.DictReader(open(os.path.join(data, "dependencies.csv"), newline="", encoding="utf-8")):
        if r.get("kind") == "0" and r["crate_id"] in targets and r["version_id"] in latest_vids:
            reqs[r["crate_id"]].append(r.get("req", "").strip())

    os.makedirs(args.work_dir, exist_ok=True)
    out = []
    for r in flagged:
        wd = os.path.join(args.work_dir, f'{r["package"]}__{r["prev"]}__{r["curr"]}')
        os.makedirs(wd, exist_ok=True)
        dirs = {}
        for tag in ("prev", "curr"):
            d = os.path.join(wd, f'{r["package"]}-{r[tag]}')
            if not os.path.isdir(d):
                d, _ = download_crate(r["package"], r[tag], wd)
            dirs[tag] = d
        cd = dirs["curr"] or ""
        toml = open(os.path.join(cd, "Cargo.toml"), encoding="utf-8", errors="replace").read() \
            if cd and os.path.isfile(os.path.join(cd, "Cargo.toml")) else ""
        has_bin = bool(cd) and (os.path.isfile(os.path.join(cd, "src", "main.rs"))
                                or os.path.isdir(os.path.join(cd, "src", "bin"))
                                or "[[bin]]" in toml)
        items = [it for v in (r.get("failed_items") or {}).values() for it in v]
        private = [it for it in items if re.search(r"(__private|::private\b)", it)]
        hidden, generated = [], False
        for path, line in item_files(items, wd):
            if not os.path.isfile(path):
                continue
            src = open(path, encoding="utf-8", errors="replace").read().splitlines()
            if any("doc(hidden)" in l for l in src[max(0, line - 6):line]):
                hidden.append(f"{os.path.basename(path)}:{line}")
            if any(GEN_RE.search(l) for l in src[:20]):
                generated = True
        lib = os.path.join(cd, "src", "lib.rs")
        if cd and os.path.isfile(lib):
            head = open(lib, encoding="utf-8", errors="replace").read().splitlines()[:40]
            generated = generated or any(GEN_RE.search(l) for l in head)
        rq = reqs.get(name2id.get(r["package"]), [])
        out.append({
            "package": r["package"], "prev": r["prev"], "curr": r["curr"], "shipped": r["shipped"],
            "required": r.get("tool_required"),
            "required_default_features": r.get("tool_required_default_features"),
            "failed_lints": " ".join(r.get("failed_lints", [])),
            "n_failed_items": len(items),
            "has_bin_target": has_bin, "private_items": len(private),
            "doc_hidden_items": len(hidden), "generated": generated,
            "dependents": len(rq),
            "eq_pinned_share": round(sum(q.startswith("=") for q in rq) / len(rq), 3) if rq else None,
        })
    path = os.path.join(args.audit_dir, "flag_context.csv")
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out[0]) if out else ["package"])
        w.writeheader()
        w.writerows(out)
    print(f"{len(out)} flagged pairs -> {path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
